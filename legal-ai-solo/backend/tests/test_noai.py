"""Rule-based reading of appellate texts (no AI). SYNTHETIC texts in the forms seen live 02.10.2026."""

from legal_ai.cassation.noai import extract_appealed, extract_vks_citations


def test_appealed_act_forms():
    cases = {
        "Образувано е по въззивна жалба, подадена от Г.Й.М., чрез адв. И.М., против решение "
        "№1659/10.05.2018 г., постановено по гр.д. №13727/2014 г. по описа на ПдРС, ІV гр.с., в частта":
            {"act": "Решение № 1659/10.05.2018", "date": "10.05.2018", "case": "13727/2014", "court": "ПдРС"},
        "Образувано е по въззивна жалба на М. И. против Решение № 261017/ 22.12.2021 г. по гр. д. "
        "№ 939/ 2020 г. на ОС – П., с което са отхвърлени":
            {"act": "Решение № 261017/22.12.2021", "date": "22.12.2021", "case": "939/2020", "court": "ОС – П"},
        "Постъпила е въззивна жалба вх. №280500/06.08.2021г. от „Р.Б.“ ЕАД против Решение № 260311 от "
        "06.07.2021г., постановено по т.д. №1110/2019г. по описа на О.С.-П., В ЧАСТТА":
            {"act": "Решение № 260311/06.07.2021", "date": "06.07.2021", "case": "1110/2019", "court": "О.С.-П"},
    }
    for text, expected in cases.items():
        assert extract_appealed(text) == expected, text


def test_appealed_act_not_guessed():
    assert extract_appealed("Производството е по реда на чл. 258 ГПК. Жалбата е допустима.") is None


def test_vks_citations_forms():
    text = (
        "с взаимния принос на двамата съпрузи /в този смисъл - решение №865/20.10.1993 г. по гр.д. "
        "№408/93 г. на ВКС, I г.о./. Следва да се съобрази разрешението, дадено по гр.д. №3048/19 г. на "
        "ВКС, II г.о., че при спор. Съдът може да допусне гласни доказателства /решение №249 от "
        "27.12.2011 г. на ВКС по гр. д. № 1037/2010 г., II г. о., ГК/. Въззивният съд следва да прецени "
        "служебно (т. 1 ТР № 1 по т. д. № 1/ 2013 г. на ВКС). Решението подлежи на обжалване пред ВКС "
        "в едномесечен срок."
    )
    got = [(c.kind, c.act_number, c.act_date, c.case_number, c.case_year, c.tr_year)
           for c in extract_vks_citations(text)]
    assert got == [
        ("решение", "865", "20.10.1993", "408", 1993, None),
        ("дело", "", "", "3048", 2019, None),
        ("решение", "249", "27.12.2011", "1037", 2010, None),
        ("ТР", "1", "", "", None, 2013),
    ]


def test_citations_ignore_plain_mentions_of_vks():
    assert extract_vks_citations("Решението подлежи на касационно обжалване пред ВКС в едномесечен срок.") == []

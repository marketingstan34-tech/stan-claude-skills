CONTEXT_MAX_EACH = 40_000
CONTEXT_MAX_TOTAL = 100_000


def context_block(docs, each: int = CONTEXT_MAX_EACH, total: int = CONTEXT_MAX_TOTAL,
                  header: str | None = None) -> str:
    """The other case documents for a prompt, each cut to `each`, all to `total` chars."""
    out, left = [], total
    for name, text in docs or ():
        if left <= 0:
            break
        part = text.strip()[:min(each, left)]
        cut = len(part) < len(text.strip())
        left -= len(part)
        out.append((header or CONTEXT_HEADER).format(name=name) + "\n" + part + ("\n[... съкратено ...]" if cut else ""))
    return ("\n\n" + "\n\n".join(out)) if out else ""

